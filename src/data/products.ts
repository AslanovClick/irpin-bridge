/** Залишки: soldOut — розміри, яких немає в жодному кольорі */
function stock(colors: ColorOption[], sizes: string[], soldOut: string[] = []): ProductVariant[] {
  return colors.flatMap((c) => sizes.map((s) => ({ color: c.name, size: s, stock: soldOut.includes(s) ? 0 : 5 })));
}

type Seed = Omit<Product, "variants" | "care" | "material" | "description"> &
  Partial<Pick<Product, "care" | "material" | "description">> & { soldOut?: string[] };

